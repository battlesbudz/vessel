const hasDatabase = configureDatabaseEnvForTests();
let skipped = 0;

if (hasDatabase) {
  const prepareResult = spawnSync(process.execPath, tsxArgs("scripts/prepare-test-database.ts"), {
    cwd: projectRoot,
    env: process.env,
    stdio: "inherit",
    shell: false,
  });
  if (prepareResult.error) {
    console.error(prepareResult.error);
    process.exit(1);
  }
  if (prepareResult.status !== 0) {
    process.exit(prepareResult.status ?? 1);
  }
}

for (const test of tests) {
  if (test.requiresDatabase && !hasDatabase) {
    skipped += 1;
    console.warn(`${test.file}: DATABASE_URL not set - skipped`);
    continue;
  }

  const result = spawnSync(process.execPath, tsxArgs(test.file), {
    cwd: projectRoot,
    env: process.env,
    stdio: "inherit",
    shell: false,
  });

  if (result.error) {
    console.error(result.error);
    process.exit(1);
  }
  if (result.status !== 0) {
    process.exit(result.status ?? 1);
  }
}

if (skipped > 0) {
  console.warn(`Skipped ${skipped} DB-backed test file(s).`);
}
